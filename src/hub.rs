//! PRISM Hub wire contract — typed telemetry events, an on-disk spool, and the
//! agent-side HTTP client that batches and ships them.
//!
//! **Shipping discipline.** `prism cmd` / PATH shims must never make a network call —
//! the CHANGELOG records a 0.57s -> 0.05s fight to get a tokenizer *off* that exact path,
//! and a blocking POST would be worse. So this module is split in two:
//!
//!   - [`spool_event`] is synchronous and allocation-only: one `write_all` under a mutex.
//!     Safe to call from the `cmd` hot path and from synchronous helpers in `cache.rs`.
//!   - Everything else (`enroll`, `fetch_config`, `flush`, [`HubSender`]) is async and
//!     touches the network. Only the long-running `serve` daemon and the `prism hub`
//!     subcommand — both already on tokio — call into that half.
//!
//! **The wire contract.** Every event type here derives `Serialize` with
//! `#[serde(rename_all = "camelCase")]`. That is the actual fix for the bug this module
//! replaces: `analytics::record_proxy_event` used to hand-build a `serde_json::json!`
//! literal with snake_case keys and POST it to a hub reading camelCase with `??`
//! fallbacks, so every field silently defaulted. Building the request body by
//! *constructing a typed value* makes that class of mismatch a compile error instead of
//! a three-month-old silent zero. [`HubEvent`] is the single source of truth for the
//! shape; `tests/fixtures/hub-events.json` (regenerated by `cargo test hub::contract`) is
//! what a hub-side schema should validate against.

use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::sync::Mutex;

