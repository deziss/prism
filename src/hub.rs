/// Tagged union of every event PRISM ships to the hub. Internally tagged on `"type"`,
/// so a `Proxy` event serializes as `{"type":"proxy", sourceIp: ..., ...}` — one flat
/// object, easy for a zod discriminated union to validate.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "camelCase")]
pub enum HubEvent {
    Proxy(ProxyEvent),
    Command(CommandEvent),
    Cache(CacheEvent),
    Session(SessionEvent),
}

/// RFC3339 timestamp for `ts` fields, factored out so every call site stamps the same way.
pub fn now() -> String {
    chrono::Utc::now().to_rfc3339()
}

/// `sent/orig`, the same derived ratio `record_proxy_event` always computed — factored
/// out so both proxy call sites (and tests) share one definition of "1.0 when nothing
/// was measured" rather than repeating the fallback.
pub fn compression_ratio(orig_tokens: u32, sent_tokens: u32) -> f32 {
    if orig_tokens > 0 {
        sent_tokens as f32 / orig_tokens as f32
    } else {
        1.0
    }
}

// ============================== disk spool =================================

static HUB_SPOOL_LOCK: Mutex<()> = Mutex::new(());

fn lock_spool() -> std::sync::MutexGuard<'static, ()> {
    HUB_SPOOL_LOCK.lock().unwrap_or_else(|poison| poison.into_inner())
}

pub fn spool_dir() -> PathBuf {
    crate::analytics::analytics_dir()
}

pub fn spool_path() -> PathBuf {
    spool_dir().join("hub_spool.jsonl")
}

/// A spool drain in flight is rotated here first, so a crash between "read" and
/// "truncate" cannot lose events — see [`rotate_spool`].
fn in_flight_path() -> PathBuf {
    spool_dir().join("hub_spool.jsonl.sending")
}

/// Append one event to the on-disk spool. Synchronous and allocation-light: one
/// `serde_json::to_string` plus one buffered `write_all` under a mutex, mirroring the
/// `PROXY_EVENTS_LOCK` pattern in `analytics.rs`. Safe to call from the `prism cmd` hot
/// path — this function never touches the network.
pub fn spool_event(event: &HubEvent) -> std::io::Result<()> {
    let mut line = serde_json::to_string(event)
        .map_err(|e| std::io::Error::new(std::io::ErrorKind::InvalidData, e))?;
    line.push('\n');
    let _guard = lock_spool();
    std::fs::create_dir_all(spool_dir())?;
    let mut f = std::fs::OpenOptions::new().create(true).append(true).open(spool_path())?;
    f.write_all(line.as_bytes())?;
    f.flush()
}

/// Atomically rotate the spool file out from under any concurrent `prism cmd` appender
/// and return its content as newline-delimited JSON. `prism cmd` processes always open
/// the spool path fresh per write (never hold a long-lived handle), so renaming it away
/// is enough: any writer racing this rename either lands in the old inode (now at
/// `in_flight_path()`, folded back in below) or opens a brand new file at the original
/// path — either way nothing is lost.
fn rotate_spool() -> std::io::Result<Option<(PathBuf, String)>> {
    let _guard = lock_spool();
    let path = spool_path();
    let in_flight = in_flight_path();

    // A previous drain that crashed or failed before `confirm_sent` left this behind.
    // Fold it back onto the live spool before rotating again, so it is not skipped.
    if in_flight.is_file() {
        let mut prior = std::fs::read_to_string(&in_flight).unwrap_or_default();
        if !prior.is_empty() && !prior.ends_with('\n') {
            prior.push('\n');
        }
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        std::fs::write(&path, format!("{prior}{current}"))?;
        let _ = std::fs::remove_file(&in_flight);
    }

    if !path.is_file() {
        return Ok(None);
    }
    std::fs::rename(&path, &in_flight)?;
    let content = std::fs::read_to_string(&in_flight)?;
    if content.trim().is_empty() {
        let _ = std::fs::remove_file(&in_flight);
        return Ok(None);
    }
    Ok(Some((in_flight, content)))
}

/// Send succeeded: the rotated file's content is durably on the hub. Drop it.
fn confirm_sent(rotated: &Path) {
    let _ = std::fs::remove_file(rotated);
}

/// Send failed: fold the rotated content back onto whatever is currently live (a
/// `prism cmd` process may have appended to a fresh spool file in the meantime) rather
/// than dropping it, then remove the temp file. This is the "only truncate after a 2xx"
/// half of the contract.
fn restore_spool(rotated: &Path) {
    let _guard = lock_spool();
    if let Ok(prior) = std::fs::read_to_string(rotated) {
        let path = spool_path();
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        let mut combined = prior;
        if !combined.is_empty() && !combined.ends_with('\n') {
            combined.push('\n');
        }
        combined.push_str(&current);
        let _ = std::fs::write(&path, combined);
    }
    let _ = std::fs::remove_file(rotated);
}

// ============================== agent identity ==============================

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AgentCredentials {
    pub hub_url: String,
    pub agent_id: String,
    pub agent_token: String,
}

fn credentials_path() -> PathBuf {
    crate::prism_config_dir().join("hub.json")
}

/// The durable agent identity written by `prism hub enroll`, or `None` if this machine
/// has never enrolled with a hub.
pub fn load_credentials() -> Option<AgentCredentials> {
    let s = std::fs::read_to_string(credentials_path()).ok()?;
    serde_json::from_str(&s).ok()
}

pub fn save_credentials(creds: &AgentCredentials) -> std::io::Result<()> {
    let dir = crate::prism_config_dir();
    std::fs::create_dir_all(&dir)?;
    std::fs::write(
        credentials_path(),
        serde_json::to_string_pretty(creds).unwrap_or_default(),
    )
}

// ============================== HTTP plumbing ================================

/// Normalise a hub base URL to its API root. The hub mounts everything under a global
/// `/api` prefix, so a bare host needs it appended, while a URL that already ends in
/// `/api` must not get it twice.
pub(crate) fn api_base(url: &str) -> String {
    let trimmed = url.trim_end_matches('/');
    if trimmed.ends_with("/api") {
        trimmed.to_string()
    } else {
        format!("{trimmed}/api")
    }
}

fn http_client() -> reqwest::Client {
    reqwest::Client::builder()
        .timeout(std::time::Duration::from_secs(15))
        .build()
        .unwrap_or_default()
}

fn hostname_string() -> String {
    std::process::Command::new("hostname")
        .output()
        .ok()
        .and_then(|o| String::from_utf8(o.stdout).ok())
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "unknown-host".to_string())
}

const MAX_BATCH: usize = 200;

/// POST one batch of already-serialized `HubEvent` JSON lines to `/api/ingest/events`.
async fn post_batch(client: &reqwest::Client, creds: &AgentCredentials, lines: &[&str]) -> Result<()> {
    let body: Vec<serde_json::Value> = lines.iter().filter_map(|l| serde_json::from_str(l).ok()).collect();
    if body.is_empty() {
        return Ok(());
    }
    let url = format!("{}/ingest/events", api_base(&creds.hub_url));
    let resp = client
        .post(&url)
        .bearer_auth(&creds.agent_token)
        .header("X-Prism-Agent-Id", &creds.agent_id)
        .json(&body)
        .send()
        .await
        .with_context(|| format!("POST {url}"))?;
    let status = resp.status();
    if status.is_success() {
        Ok(())
    } else {
        let text = resp.text().await.unwrap_or_default();
        anyhow::bail!("hub ingest returned {status}: {text}");
    }
}

/// Drain the on-disk spool: rotate it out, send in `MAX_BATCH`-sized chunks, and only
/// drop the rotated file once every chunk in it has been accepted. On any failure the
/// whole rotated file (including chunks already accepted this pass) is folded back onto
/// the live spool for a later retry — an accepted at-least-once duplicate is preferable
/// to a silently dropped event.
pub async fn flush(creds: &AgentCredentials) -> FlushOutcome {
    let client = http_client();
    let mut sent = 0usize;
    let mut batches = 0usize;
    let mut failed = false;

    loop {
        match rotate_spool() {
            Ok(Some((rotated, content))) => {
                let lines: Vec<&str> = content.lines().filter(|l| !l.trim().is_empty()).collect();
                let mut all_ok = true;
                for chunk in lines.chunks(MAX_BATCH) {
                    match post_batch(&client, creds, chunk).await {
                        Ok(()) => {
                            batches += 1;
                            sent += chunk.len();
                        }
                        Err(e) => {
                            tracing::warn!("hub flush: {e}");
                            all_ok = false;
                            break;
                        }
                    }
                }
                if all_ok {
                    confirm_sent(&rotated);
                } else {
                    restore_spool(&rotated);
                    failed = true;
                    break;
                }
            }
            Ok(None) => break,
            Err(e) => {
                tracing::warn!("hub flush: could not rotate spool: {e}");
                failed = true;
                break;
            }
        }
    }

    FlushOutcome { sent, batches, failed }
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct FlushOutcome {
    pub sent: usize,
    pub batches: usize,
    pub failed: bool,
}

