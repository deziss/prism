#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct EnrollRequest<'a> {
    join_token: &'a str,
    hostname: String,
    os: &'static str,
    prism_version: &'static str,
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct EnrollResponse {
    agent_id: String,
    agent_token: String,
}

/// Exchange a short-lived team join token for a durable agent token, and persist both
/// alongside the agent id under the global config dir.
pub async fn enroll(hub_url: &str, join_token: &str) -> Result<AgentCredentials> {
    let client = http_client();
    let url = format!("{}/agents/enroll", api_base(hub_url));
    let req = EnrollRequest {
        join_token,
        hostname: hostname_string(),
        os: std::env::consts::OS,
        prism_version: env!("CARGO_PKG_VERSION"),
    };
    let resp = client
        .post(&url)
        .json(&req)
        .send()
        .await
        .with_context(|| format!("connecting to hub at {url}"))?;
    let status = resp.status();
    if !status.is_success() {
        let text = resp.text().await.unwrap_or_default();
        anyhow::bail!("enroll failed: hub returned {status}: {text}");
    }
    let parsed: EnrollResponse = resp.json().await.context("parsing enroll response")?;
    let creds = AgentCredentials {
        hub_url: hub_url.trim_end_matches('/').to_string(),
        agent_id: parsed.agent_id,
        agent_token: parsed.agent_token,
    };
    save_credentials(&creds)?;
    Ok(creds)
}

/// Fetch hub-enforced policy for this agent and write it to `<data>/hub-config.yaml`,
/// where `config::merge_all` picks it up as the highest-precedence layer.
pub async fn fetch_config(creds: &AgentCredentials) -> Result<crate::config::PrismConfig> {
    let client = http_client();
    let url = format!("{}/agents/{}/config", api_base(&creds.hub_url), creds.agent_id);
    let resp = client
        .get(&url)
        .bearer_auth(&creds.agent_token)
        .send()
        .await
        .with_context(|| format!("connecting to hub at {url}"))?;
    let status = resp.status();
    if !status.is_success() {
        let text = resp.text().await.unwrap_or_default();
        anyhow::bail!("fetch config failed: hub returned {status}: {text}");
    }
    let text = resp.text().await.context("reading hub config response")?;
    // The hub side is a different repo/agent; be lenient about whether it answers with
    // the YAML we persist locally or a JSON encoding of the same shape.
    let cfg: crate::config::PrismConfig = serde_yaml::from_str(&text)
        .or_else(|_| serde_json::from_str(&text))
        .context("hub policy did not parse as PrismConfig (YAML or JSON)")?;
    let path = crate::prism_data_dir().join("hub-config.yaml");
    std::fs::write(&path, serde_yaml::to_string(&cfg).unwrap_or_default())
        .with_context(|| format!("writing {}", path.display()))?;
    Ok(cfg)
}

/// Send one synthetic event and report success/failure. With `hub_url_override` set this
/// needs no prior enrollment — point it at `python3 -m http.server` or `nc -l` and check
/// that the request body keys are camelCase, which is the manual proof the contract is
/// wired correctly end to end.
pub async fn send_test_event(hub_url_override: Option<String>) -> Result<()> {
    let creds = match hub_url_override {
        Some(url) => AgentCredentials {
            hub_url: url.trim_end_matches('/').to_string(),
            agent_id: "test-agent".to_string(),
            agent_token: "test-token".to_string(),
        },
        None => load_credentials()
            .context("not enrolled — run `prism hub enroll` first, or pass --url to test against a scratch endpoint")?,
    };
    let client = http_client();
    let ev = HubEvent::Session(SessionEvent {
        event: SessionEventKind::Start,
        client: "prism-hub-test".to_string(),
        project: "prism".to_string(),
        cwd_hash: "0".repeat(16),
        ts: now(),
    });
    let line = serde_json::to_string(&ev)?;
    post_batch(&client, &creds, &[line.as_str()]).await
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct HubStatus {
    pub enrolled: bool,
    pub hub_url: Option<String>,
    pub agent_id: Option<String>,
    pub spool_events: usize,
    pub spool_bytes: u64,
}

pub fn status() -> HubStatus {
    let creds = load_credentials();
    let (events, bytes) = match std::fs::read_to_string(spool_path()) {
        Ok(s) => (s.lines().filter(|l| !l.trim().is_empty()).count(), s.len() as u64),
        Err(_) => (0, 0),
    };
    HubStatus {
        enrolled: creds.is_some(),
        hub_url: creds.as_ref().map(|c| c.hub_url.clone()),
        agent_id: creds.as_ref().map(|c| c.agent_id.clone()),
        spool_events: events,
        spool_bytes: bytes,
    }
}

// ============================== live sender (the `serve` daemon) ==============================

/// Bounded channel + background batching task owned by `prism serve`. Proxy call sites
/// build a `HubEvent` and call [`HubSender::send`]; this never blocks the request path —
/// a full channel (the hub has been unreachable long enough to back up 1024 events)
/// falls back to [`spool_event`], the same disk path `prism cmd` uses, so nothing is
/// dropped, only delayed until the next `prism hub flush` or periodic drain.
pub struct HubSender {
    tx: Option<tokio::sync::mpsc::Sender<HubEvent>>,
}

impl HubSender {
    /// A sender with no background task at all — every `send()` goes straight to the
    /// disk spool. Used by tests and anywhere a `HubSender` is required structurally but
    /// no real hub connection should be attempted.
    pub fn inert() -> Self {
        HubSender { tx: None }
    }

    /// Spawn the background task if this agent is enrolled; otherwise return an inert
    /// sender that spools every event to disk (still recoverable via `prism hub flush`
    /// once `prism hub enroll` has run).
    pub fn spawn() -> Self {
        let Some(creds) = load_credentials() else {
            tracing::info!("hub: not enrolled — proxy telemetry stays local (see `prism hub enroll`)");
            return HubSender { tx: None };
        };

        let (tx, rx) = tokio::sync::mpsc::channel::<HubEvent>(1024);
        tokio::spawn(Self::run(creds, rx));
        HubSender { tx: Some(tx) }
    }

    async fn run(creds: AgentCredentials, mut rx: tokio::sync::mpsc::Receiver<HubEvent>) {
        // Whatever this agent (or `prism cmd` invocations while `serve` was down) already
        // spooled goes out before anything new.
        let startup = flush(&creds).await;
        tracing::info!(
            "hub: startup drain sent {} event(s) in {} batch(es){}",
            startup.sent,
            startup.batches,
            if startup.failed { " (hub unreachable, will retry)" } else { "" }
        );

        let client = http_client();
        let mut batch: Vec<HubEvent> = Vec::with_capacity(MAX_BATCH);
        let mut tick = tokio::time::interval(std::time::Duration::from_secs(2));
        tick.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);

        loop {
            tokio::select! {
                biased;
                maybe_ev = rx.recv() => {
                    match maybe_ev {
                        Some(ev) => {
                            batch.push(ev);
                            if batch.len() >= MAX_BATCH {
                                Self::send_batch(&client, &creds, &mut batch).await;
                            }
                        }
                        None => break, // sender dropped: process is shutting down
                    }
                }
                _ = tick.tick() => {
                    if !batch.is_empty() {
                        Self::send_batch(&client, &creds, &mut batch).await;
                    }
                    let _ = flush(&creds).await;
                }
            }
        }
        if !batch.is_empty() {
            Self::send_batch(&client, &creds, &mut batch).await;
        }
    }

    /// Send with exponential backoff; on final failure, spool the batch rather than
    /// drop it.
    async fn send_batch(client: &reqwest::Client, creds: &AgentCredentials, batch: &mut Vec<HubEvent>) {
        const MAX_ATTEMPTS: u32 = 3;
        let lines: Vec<String> = batch.iter().filter_map(|e| serde_json::to_string(e).ok()).collect();
        let refs: Vec<&str> = lines.iter().map(String::as_str).collect();

        for attempt in 1..=MAX_ATTEMPTS {
            match post_batch(client, creds, &refs).await {
                Ok(()) => {
                    batch.clear();
                    return;
                }
                Err(e) => {
                    tracing::warn!("hub: POST attempt {attempt}/{MAX_ATTEMPTS} failed: {e}");
                    if attempt < MAX_ATTEMPTS {
                        let backoff = std::time::Duration::from_millis(300 * 2u64.pow(attempt));
                        tokio::time::sleep(backoff).await;
                    }
                }
            }
        }
        for ev in batch.drain(..) {
            let _ = spool_event(&ev);
        }
    }

    /// Queue an event. Never blocks: falls back to the disk spool on backpressure or
    /// when there is no live sender (not enrolled).
    pub fn send(&self, event: HubEvent) {
        let Some(tx) = &self.tx else {
            let _ = spool_event(&event);
            return;
        };
        if let Err(e) = tx.try_send(event) {
            use tokio::sync::mpsc::error::TrySendError;
            let dropped = match e {
                TrySendError::Full(ev) | TrySendError::Closed(ev) => ev,
            };
            let _ = spool_event(&dropped);
        }
    }
}

