    #[test]
    fn spool_rotate_confirm_round_trip() {
        let dir = std::env::temp_dir().join(format!(
            "prism-hub-spool-test-{}-{:?}",
            std::process::id(),
            std::time::SystemTime::now()
        ));
        std::fs::create_dir_all(&dir).unwrap();
        // SAFETY: single-threaded env mutation scoped to this test's own temp dir name.
        unsafe { std::env::set_var("PRISM_DATA_DIR", &dir) };

        let ev = HubEvent::Command(CommandEvent {
            tool: "ls".to_string(),
            subcommand: String::new(),
            exit_code: 0,
            duration_ms: 5,
            input_bytes: 10,
            output_bytes: 10,
            filtered_bytes: 0,
            truncated: false,
            via_shim: false,
            ts: now(),
        });
        spool_event(&ev).unwrap();
        assert_eq!(status().spool_events, 1);

        let (rotated, content) = rotate_spool().unwrap().expect("one event should be present");
        assert!(content.contains("\"tool\":\"ls\""));
        assert_eq!(status().spool_events, 0, "rotate must remove the live spool file");

        // Failure path: content must come back.
        restore_spool(&rotated);
        assert_eq!(status().spool_events, 1);

        let (rotated2, _) = rotate_spool().unwrap().unwrap();
        confirm_sent(&rotated2);
        assert_eq!(status().spool_events, 0);

        unsafe { std::env::remove_var("PRISM_DATA_DIR") };
        let _ = std::fs::remove_dir_all(&dir);
    }
